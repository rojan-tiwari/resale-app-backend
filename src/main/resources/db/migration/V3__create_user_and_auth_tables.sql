-- =============================================================================
-- V3: Identity, roles, profiles and token tables
--
-- Delete policy for users: accounts are soft-deleted (status = 'DELETED').
-- Business data that references a user (listings, conversations, messages,
-- reports) uses ON DELETE RESTRICT so a hard delete cannot silently destroy it.
-- Purely personal/ephemeral data (profile, roles, tokens) cascades.
-- =============================================================================

CREATE TABLE roles (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(30)  NOT NULL,
    description VARCHAR(200),
    CONSTRAINT uq_roles_name UNIQUE (name)
);

CREATE TABLE users (
    id                    UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    email                 VARCHAR(254) NOT NULL,
    password_hash         VARCHAR(100) NOT NULL,           -- BCrypt (60 chars) or Argon2; never returned by the API
    status                VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    email_verified        BOOLEAN      NOT NULL DEFAULT FALSE,
    suspended_at          TIMESTAMPTZ,
    suspension_reason     VARCHAR(500),
    failed_login_attempts INTEGER      NOT NULL DEFAULT 0,
    locked_until          TIMESTAMPTZ,
    last_login_at         TIMESTAMPTZ,
    created_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version               BIGINT       NOT NULL DEFAULT 0,  -- optimistic locking
    CONSTRAINT uq_users_email UNIQUE (email),
    -- Emails are normalised to lower case by the application; the CHECK makes the
    -- UNIQUE constraint effectively case-insensitive and guards against bad writes.
    CONSTRAINT chk_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'DELETED')),
    CONSTRAINT chk_users_failed_logins CHECK (failed_login_attempts >= 0)
);

CREATE INDEX idx_users_status_created ON users (status, created_at DESC);

CREATE TRIGGER trg_users_updated_at
    BEFORE UPDATE ON users
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

CREATE TABLE user_roles (
    user_id    UUID        NOT NULL,
    role_id    INTEGER     NOT NULL,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (id) ON DELETE RESTRICT
);

CREATE INDEX idx_user_roles_role ON user_roles (role_id);

CREATE TABLE user_profiles (
    user_id            UUID         PRIMARY KEY,
    display_name       VARCHAR(80)  NOT NULL,
    phone              VARCHAR(20),                       -- normalised E.164, e.g. +9779812345678
    show_phone         BOOLEAN      NOT NULL DEFAULT FALSE, -- explicit consent before the number is public
    bio                VARCHAR(500),
    avatar_storage_key VARCHAR(255),
    province_id        INTEGER,
    district_id        INTEGER,
    municipality_id    INTEGER,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT fk_user_profiles_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    -- Composite FKs guarantee province/district/municipality are mutually consistent.
    -- (MATCH SIMPLE: not checked while any column of the pair is NULL.)
    CONSTRAINT fk_user_profiles_district FOREIGN KEY (district_id, province_id)
        REFERENCES districts (id, province_id),
    CONSTRAINT fk_user_profiles_municipality FOREIGN KEY (municipality_id, district_id)
        REFERENCES municipalities (id, district_id),
    CONSTRAINT chk_user_profiles_location_chain CHECK (
        (district_id IS NULL OR province_id IS NOT NULL)
        AND (municipality_id IS NULL OR district_id IS NOT NULL)),
    -- Nepali mobile numbers in E.164 form: +977 followed by 9[6-8] and 8 more digits.
    CONSTRAINT chk_user_profiles_phone CHECK (phone IS NULL OR phone ~ '^\+9779[678][0-9]{8}$'),
    CONSTRAINT chk_user_profiles_display_name CHECK (char_length(btrim(display_name)) >= 2)
);

CREATE INDEX idx_user_profiles_province ON user_profiles (province_id);

CREATE TRIGGER trg_user_profiles_updated_at
    BEFORE UPDATE ON user_profiles
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Refresh tokens are stored only as SHA-256 hashes. All tokens that descend from one
-- login share a family_id: re-use of an already-rotated token revokes the whole family.
CREATE TABLE refresh_tokens (
    id             UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        UUID         NOT NULL,
    family_id      UUID         NOT NULL,
    token_hash     CHAR(64)     NOT NULL,
    issued_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at     TIMESTAMPTZ  NOT NULL,
    revoked_at     TIMESTAMPTZ,
    revoked_reason VARCHAR(30),
    replaced_by_id UUID,
    ip_address     VARCHAR(45),
    user_agent     VARCHAR(300),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_refresh_tokens_replaced_by FOREIGN KEY (replaced_by_id)
        REFERENCES refresh_tokens (id) ON DELETE SET NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT chk_refresh_tokens_expiry CHECK (expires_at > issued_at),
    CONSTRAINT chk_refresh_tokens_reason CHECK (
        revoked_reason IS NULL OR revoked_reason IN ('ROTATED', 'LOGOUT', 'REUSE_DETECTED', 'PASSWORD_CHANGED', 'ADMIN'))
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX idx_refresh_tokens_family ON refresh_tokens (family_id);
CREATE INDEX idx_refresh_tokens_expires ON refresh_tokens (expires_at);   -- housekeeping job

-- Password reset tokens: single use, short lived, stored as SHA-256 hashes.
CREATE TABLE password_reset_tokens (
    id         UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id    UUID        NOT NULL,
    token_hash CHAR(64)    NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT uq_password_reset_tokens_hash UNIQUE (token_hash),
    CONSTRAINT chk_password_reset_tokens_expiry CHECK (expires_at > created_at)
);

CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens (user_id);
CREATE INDEX idx_password_reset_tokens_expires ON password_reset_tokens (expires_at);
