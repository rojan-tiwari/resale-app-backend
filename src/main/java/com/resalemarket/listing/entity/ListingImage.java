package com.resalemarket.listing.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import java.time.Instant;
import java.util.UUID;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.Generated;
import org.hibernate.generator.EventType;

/**
 * One photo of a listing: the metadata and the key under which {@code StorageService} holds the file (never the file itself).
 *
 * <p>Invariant kept by the service and, for the parts that can be, by the database: the images of a listing are numbered
 * {@code 0..n-1} without gaps in display order, there are at most {@link #MAX_PER_LISTING}, and <b>the primary image is the
 * one at position 0</b>. "Make this the main photo" therefore means moving it to the front.
 */
@Entity
@Table(name = "listing_images")
@Getter
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class ListingImage {

    /** Also enforced by {@code chk_listing_images_sort_order} (positions 0 to 7). */
    public static final int MAX_PER_LISTING = 8;

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "listing_id", nullable = false, updatable = false)
    private UUID listingId;

    /** Opaque key understood by {@code StorageService}, generated by the server. */
    @Column(name = "storage_key", nullable = false, updatable = false, length = 255)
    private String storageKey;

    @Column(name = "content_type", nullable = false, updatable = false, length = 50)
    private String contentType;

    @Column(name = "size_bytes", nullable = false, updatable = false)
    private long sizeBytes;

    @Column(updatable = false)
    private Integer width;

    @Column(updatable = false)
    private Integer height;

    @Column(name = "sort_order", nullable = false)
    private int sortOrder;

    @Column(name = "is_primary", nullable = false)
    private boolean primary;

    @Generated(event = EventType.INSERT)
    @Column(name = "created_at", nullable = false, insertable = false, updatable = false)
    private Instant createdAt;

    public static ListingImage of(
            UUID listingId, String storageKey, String contentType, long sizeBytes, int width, int height, int sortOrder) {
        ListingImage image = new ListingImage();
        image.listingId = listingId;
        image.storageKey = storageKey;
        image.contentType = contentType;
        image.sizeBytes = sizeBytes;
        image.width = width;
        image.height = height;
        image.sortOrder = sortOrder;
        image.primary = sortOrder == 0;
        return image;
    }

    /** Puts the image at {@code position}; the one at 0 is the primary image. */
    public void moveTo(int position) {
        this.sortOrder = position;
        this.primary = position == 0;
    }
}
