-- =============================================================================
-- V4: Categories (two-level tree: category -> subcategory)
--
-- Stored in the database (not hardcoded) so admins can manage them.
-- UNIQUE (id, parent_id) is the target of listings' composite foreign key, which
-- guarantees that a listing's subcategory really belongs to its category.
-- =============================================================================

CREATE TABLE categories (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   INTEGER,
    name        VARCHAR(100) NOT NULL,
    slug        VARCHAR(120) NOT NULL,
    icon        VARCHAR(50),                              -- icon key resolved by the frontend
    description VARCHAR(300),
    sort_order  INTEGER      NOT NULL DEFAULT 0,
    is_active   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT fk_categories_parent FOREIGN KEY (parent_id) REFERENCES categories (id) ON DELETE RESTRICT,
    CONSTRAINT uq_categories_slug UNIQUE (slug),
    CONSTRAINT uq_categories_parent_name UNIQUE (parent_id, name),
    CONSTRAINT uq_categories_id_parent UNIQUE (id, parent_id),
    CONSTRAINT chk_categories_not_self_parent CHECK (parent_id IS NULL OR parent_id <> id)
);

-- UNIQUE (parent_id, name) does not de-duplicate root categories because NULLs are distinct.
CREATE UNIQUE INDEX ux_categories_root_name ON categories (name) WHERE parent_id IS NULL;
CREATE INDEX idx_categories_parent_sort ON categories (parent_id, sort_order);

CREATE TRIGGER trg_categories_updated_at
    BEFORE UPDATE ON categories
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Enforce the two-level depth limit at the database level.
CREATE OR REPLACE FUNCTION enforce_category_depth()
RETURNS TRIGGER AS
$$
BEGIN
    IF NEW.parent_id IS NOT NULL THEN
        IF EXISTS (SELECT 1 FROM categories WHERE id = NEW.parent_id AND parent_id IS NOT NULL) THEN
            RAISE EXCEPTION 'Categories support only two levels: parent % is already a subcategory', NEW.parent_id
                USING ERRCODE = 'check_violation';
        END IF;
        IF EXISTS (SELECT 1 FROM categories WHERE parent_id = NEW.id) THEN
            RAISE EXCEPTION 'Category % has subcategories and cannot become a subcategory itself', NEW.id
                USING ERRCODE = 'check_violation';
        END IF;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_categories_depth
    BEFORE INSERT OR UPDATE OF parent_id ON categories
    FOR EACH ROW EXECUTE FUNCTION enforce_category_depth();
