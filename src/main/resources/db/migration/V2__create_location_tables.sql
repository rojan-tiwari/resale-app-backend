-- =============================================================================
-- V2: Nepal location hierarchy  (province -> district -> municipality)
--
-- Locations are structured reference data, never free-form strings.
-- The composite UNIQUE constraints (id, parent_id) exist so that child tables
-- (listings, user_profiles) can use composite foreign keys that make it
-- impossible to store e.g. a Kathmandu municipality under Gandaki province.
-- name_ne columns are reserved for the future Nepali-language localisation.
-- =============================================================================

CREATE TABLE provinces (
    id      INTEGER      PRIMARY KEY,                -- the official province number (1..7)
    name    VARCHAR(60)  NOT NULL,
    slug    VARCHAR(80)  NOT NULL,
    name_ne VARCHAR(80),
    CONSTRAINT uq_provinces_name UNIQUE (name),
    CONSTRAINT uq_provinces_slug UNIQUE (slug)
);

CREATE TABLE districts (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    province_id INTEGER      NOT NULL,
    name        VARCHAR(80)  NOT NULL,
    slug        VARCHAR(100) NOT NULL,
    name_ne     VARCHAR(100),
    CONSTRAINT fk_districts_province FOREIGN KEY (province_id)
        REFERENCES provinces (id) ON DELETE RESTRICT,
    CONSTRAINT uq_districts_name UNIQUE (name),
    CONSTRAINT uq_districts_slug UNIQUE (slug),
    CONSTRAINT uq_districts_id_province UNIQUE (id, province_id)
);

CREATE INDEX idx_districts_province ON districts (province_id);

CREATE TABLE municipalities (
    id          INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id INTEGER      NOT NULL,
    name        VARCHAR(100) NOT NULL,
    slug        VARCHAR(120) NOT NULL,
    type        VARCHAR(30)  NOT NULL DEFAULT 'MUNICIPALITY',
    is_major    BOOLEAN      NOT NULL DEFAULT FALSE,   -- shown first in location pickers
    name_ne     VARCHAR(120),
    CONSTRAINT fk_municipalities_district FOREIGN KEY (district_id)
        REFERENCES districts (id) ON DELETE RESTRICT,
    CONSTRAINT uq_municipalities_slug UNIQUE (slug),
    CONSTRAINT uq_municipalities_district_name UNIQUE (district_id, name),
    CONSTRAINT uq_municipalities_id_district UNIQUE (id, district_id),
    CONSTRAINT chk_municipalities_type CHECK (
        type IN ('METROPOLITAN', 'SUB_METROPOLITAN', 'MUNICIPALITY', 'RURAL_MUNICIPALITY'))
);

CREATE INDEX idx_municipalities_district ON municipalities (district_id);
CREATE INDEX idx_municipalities_major ON municipalities (name) WHERE is_major;
